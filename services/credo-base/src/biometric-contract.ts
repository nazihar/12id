/**
 * HTTP contract between platform-api (caller) and biometric-service (Phase 6, 15-phase-6-biometric.md B1).
 * Both sides validate with these schemas. biometric-service is on a private network and requires
 * its own token in INTERNAL_TOKEN_HEADER (not the agent token, review H2).
 *
 * No schema here ever carries a vendor secret back to the caller, and no response carries an image.
 */
import { z } from 'zod'

export { INTERNAL_TOKEN_HEADER } from './endorsement-contract.ts'

export const tenantIdSchema = z.string().min(1).max(200)

/** Thresholds are normalized 0–100 scores; the check snapshots them at creation. */
export const thresholdsSchema = z.object({
  minLivenessScore: z.number().min(0).max(100),
  minMatchScore: z.number().min(0).max(100),
})
export type Thresholds = z.infer<typeof thresholdsSchema>

export const checkStatusSchema = z.enum(['pending', 'passed', 'failed', 'expired', 'cancelled'])
export type CheckStatus = z.infer<typeof checkStatusSchema>

export const decisionReasonSchema = z.enum([
  'passed',
  'not_live',
  'liveness_below_threshold',
  'no_face',
  'match_below_threshold',
  'vendor_failed',
  'vendor_expired',
])
export type DecisionReason = z.infer<typeof decisionReasonSchema>

// ---- provider catalogue and tenant configuration ----

export const providerCatalogueEntry = z.object({
  id: z.string(),
  displayName: z.string(),
  /** JSON Schema of the tenant-supplied configuration; the console renders its form from it. */
  configSchema: z.record(z.string(), z.unknown()),
  /** The device add-on that can run this provider's capture. */
  captureModule: z.object({ provider: z.string(), minVersion: z.number().int() }),
})
export const providerCatalogueResponse = z.object({ providers: z.array(providerCatalogueEntry) })

export const providerStatusSchema = z.enum(['untested', 'ok', 'failed'])

/** What GET returns: the non-secret part of the configuration only. */
export const tenantProviderResponse = z.object({
  tenantId: z.string(),
  /** Generated by us per tenant; the tenant puts it in its role's trust policy. */
  externalId: z.string(),
  provider: z
    .object({
      id: z.string(),
      publicConfig: z.record(z.string(), z.unknown()),
      status: providerStatusSchema,
      lastTestedAt: z.string().nullable(),
      lastError: z.string().nullable(),
      updatedAt: z.string(),
    })
    .nullable(),
})
export type TenantProviderResponse = z.infer<typeof tenantProviderResponse>

/** A configuration that waits for a second person: its name and its non-secret part, never the rest. */
export const pendingProviderResponse = z.object({ providerId: z.string(), publicConfig: z.record(z.string(), z.unknown()) })
export type PendingProviderResponse = z.infer<typeof pendingProviderResponse>

export const putTenantProviderBody = z.object({
  providerId: z.string().min(1).max(100),
  config: z.record(z.string(), z.unknown()),
})

export const providerTestResponse = z.object({ status: providerStatusSchema, error: z.string().nullable() })

// ---- checks and sessions ----

/** Base64 of a JPEG or PNG, at most 5 MB decoded (AWS CompareFaces limit). */
export const referenceImageSchema = z.string().min(100).max(7_000_000)

export const createCheckBody = z.object({
  tenantId: tenantIdSchema,
  purpose: z.enum(['issue', 'proof']),
  referenceImage: referenceImageSchema,
  thresholds: thresholdsSchema,
  maxAttempts: z.number().int().min(1).max(5),
  ttlSeconds: z.number().int().min(60).max(86_400),
})
export type CreateCheckBody = z.infer<typeof createCheckBody>

export const createCheckResponse = z.object({
  checkId: z.string().uuid(),
  providerId: z.string(),
  expiresAt: z.string(),
})

export const startSessionResponse = z.object({
  sessionId: z.string().uuid(),
  /** The vendor's own session id (e.g. AWS SessionId), for the audit log and cross-checks in the tenant's vendor account. */
  vendorSessionId: z.string(),
  providerId: z.string(),
  captureModule: z.object({ provider: z.string(), minVersion: z.number().int() }),
  /** Opaque to platform-api and the core SDK; only the device add-on reads it. May hold short-lived credentials. */
  clientConfig: z.unknown(),
  attempt: z.number().int(),
  attemptsRemaining: z.number().int(),
})

export const completeSessionBody = z.object({ clientOutput: z.unknown() })

export const attemptResultSchema = z.object({
  decision: z.enum(['passed', 'failed']),
  reason: decisionReasonSchema,
  livenessScore: z.number().nullable(),
  matchScore: z.number().nullable(),
})

export const completeSessionResponse = z.object({
  sessionId: z.string().uuid(),
  vendorSessionId: z.string(),
  attempt: z.number().int(),
  result: attemptResultSchema,
  check: z.object({ status: checkStatusSchema, attemptsRemaining: z.number().int() }),
})
export type CompleteSessionResponse = z.infer<typeof completeSessionResponse>

export const checkResponse = z.object({
  checkId: z.string().uuid(),
  tenantId: z.string(),
  purpose: z.enum(['issue', 'proof']),
  providerId: z.string(),
  status: checkStatusSchema,
  thresholds: thresholdsSchema,
  attempts: z.number().int(),
  maxAttempts: z.number().int(),
  expiresAt: z.string(),
  decidedAt: z.string().nullable(),
  sessions: z.array(
    z.object({
      sessionId: z.string().uuid(),
      attempt: z.number().int(),
      /** null once the check was erased (Phase 7 H1). */
      vendorSessionId: z.string().nullable(),
      status: z.enum(['started', 'completing', 'completed']),
      startedAt: z.string(),
      completedAt: z.string().nullable(),
      result: attemptResultSchema.nullable(),
    })
  ),
})
export type CheckResponse = z.infer<typeof checkResponse>

export const errorResponse = z.object({ error: z.string(), reason: z.string() })
